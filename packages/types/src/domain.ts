/* -------------------------------------------------------------------------- */
/* Primitive aliases                                                           */
/*                                                                            */
/* Plain `string` aliases rather than branded types: they document intent at  */
/* the call site without forcing casts at every boundary.                     */
/* -------------------------------------------------------------------------- */

/** `2026-10-09T21:05:00.000Z`, always UTC. */
export type IsoDateTimeString = string;

/** `2026-10-09`, a calendar date in Europe/Amsterdam. */
export type IsoDateString = string;

/** `19:30`, a wall-clock time in Europe/Amsterdam. */
export type LocalTimeString = string;

/** A UUID v4 generated by the API. */
export type Uuid = string;

/**
 * A score as the API exchanges it.
 *
 * Numbers for `ScoreType.NUMBER` (up to three decimals) and whole milliseconds
 * for `ScoreType.TIME`. Both fit a JavaScript number safely; the database
 * column is DECIMAL(16,3).
 */
export type ScoreValue = number;
